#pragma once

// 更新・描画、任意の初期化・終了、破棄要求を提供するゲームオブジェクトの抽象基底クラス。
// 派生オブジェクトの所有、管理コンテナからの削除、各メソッドの自動呼出は担当しない。
// このHeaderの実装はC++の言語機能だけを使うため、標準・Windows・独自Headerのincludeは必要ない。

// 派生クラスにUpdateとDrawの実装箇所を提供する。生成・更新・描画・終了の呼出順は利用側が管理する。
class GameObject
{
public:
  //========= 生成・破棄関数=========
  // 仮想デストラクターにより、基底ポインター経由で破棄した場合も派生デストラクターの実行へつなげる。
  // Uninitを自動では呼ばない。派生実装が明示終了を必要とする場合、その呼出は利用側または派生側の責務。
  virtual ~GameObject() = default;

  //========= 純粋仮想関数=========
  // フレーム更新の実装箇所。基底実装はなく、具象派生クラス側で実装する。
  // deltaTime: この更新へ渡す経過秒数。基底側では範囲・有限性を検証せず、単位や適用は派生実装が扱う。
  // 破棄要求フラグを判定して更新を省略する処理は、この基底クラスにはない。
  virtual void Update(float deltaTime) = 0;
  // 表示内容の描画を派生クラスで実装する。描画先や必要なSystemの取得・状態設定は派生側が扱う。
  // 呼出回数や更新との順序はこのクラスでは制御しない。破棄要求後の描画を自動停止する機能もない。
  virtual void Draw() = 0;

  //========= 任意実装関数=========
  // 戻り値を持たない初期化の実装箇所。基底実装は何もしない。Initを内部で呼ぶ処理もない。
  virtual void Initialize() {}
  // 成否を返す初期化の実装箇所。基底実装は常にtrueだが、Resource生成や初期化完了の記録は行わない。
  // 戻り値: 基底のtrueは何も行わず成功扱いで戻ることを表す。派生実装の失敗や後始末は利用側と別途整合させる。
  // Initializeとの呼出順や連動を基底側で保証せず、二つの入口を統合・削除する変更もしない。
  virtual bool Init() { return true; }
  // 明示的な終了処理の実装箇所。基底実装は何もしない。二重終了防止や部分初期化の解放は派生側の責務。
  // デストラクターとの自動連動、破棄要求フラグのリセットは行わない。
  virtual void Uninit() {}

  //========= 状態変更関数=========
  // 破棄要求をtrueへ設定する。その場でdelete・Uninit・コンテナ削除を実行する処理ではない。
  // 繰り返し呼んでもtrueを代入するだけで、要求回数を蓄積したり、別の通知を発生させたりしない。
  void SetDestroyRequested() { m_isDestroyRequested = true; }

  //========= Getter関数=========
  // 破棄要求の有無を返す。trueでも実際の破棄・終了の完了を表さず、取得しても要求を消費しない。
  [[nodiscard]] bool IsDestroyRequested() const { return m_isDestroyRequested; }

private:
  //========= 状態管理=========
  // 初期値falseは要求なし、SetDestroyRequested後のtrueは要求あり。このフラグ自体はオブジェクトを所有しない。
  // 基底クラスの公開操作に取り消し機能はなく、Initialize・Init・Uninitでも初期値へ戻さない。
  bool m_isDestroyRequested{};
};